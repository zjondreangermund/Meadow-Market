import assert from 'node:assert/strict';
import {SAFE_LINE,zoneAt,newFrontierState,normaliseState,simulateNeeds,collectAt,consume,depositAtHome,sellAtMarket,buySupplies,knockout} from '../dist/frontier-rules.js';
assert.equal(zoneAt(SAFE_LINE-1),'safe');assert.equal(zoneAt(SAFE_LINE),'frontier');assert.equal(zoneAt(70),'red');
const s=newFrontierState();
assert.equal(collectAt(s,'scrap',1000).ok,false);
assert.equal(collectAt(s,'crop',1000).ok,true);
assert.equal(collectAt(s,'crop',1001).ok,false);
assert.equal(s.storage.maize,7);
s.x=85;
assert.equal(collectAt(s,'raid',1000).ok,true);
assert.equal(s.pack.parts,2);
assert.equal(collectAt(s,'raid',1002).ok,false);
assert.equal(collectAt(s,'scrap',1000).ok,true);
const before=s.hunger;simulateNeeds(s,1);assert(s.hunger<before);
assert.equal(depositAtHome(s).ok,false);
const cash=s.coins;knockout(s);assert.equal(s.pack.parts,0);assert.equal(s.storage.maize,7);assert.equal(s.coins,cash);
s.x=85;collectAt(s,'scrap',14000);s.x=0;
assert.equal(depositAtHome(s).ok,true);
assert.equal(s.storage.scrap,2);
assert.equal(sellAtMarket(s,'scrap',2).ok,true);
assert.equal(s.coins,cash+28);
assert.equal(buySupplies(s,'rations',1).ok,true);
assert.equal(consume(s,'rations').ok,true);
const restored=normaliseState({...s,pack:{...s.pack,scrap:-50000},coins:Infinity});
assert.equal(restored.pack.scrap,0);assert.equal(restored.coins,160);
assert.equal(restored.riding,false);
console.log('Frontier rules tests passed');
